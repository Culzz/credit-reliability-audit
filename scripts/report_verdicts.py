"""Render the post-freeze verdict register from the confirmatory table.

`protocol/HYPOTHESES.md` is frozen protocol text and is never edited. This
script writes the separate outcome record `protocol/HYPOTHESES_VERDICTS.md`
from `reports/tables/real_statistics.csv` (never hand-typed), plus the
noise-floor pair counts that bound each test's precision.

Outputs: protocol/HYPOTHESES_VERDICTS.md
Use    : python -m uv run python -m scripts.report_verdicts
"""

from __future__ import annotations

import pandas as pd

from scripts._common import REPO_ROOT, TABLES

OUT = REPO_ROOT / "protocol" / "HYPOTHESES_VERDICTS.md"
CONFIRMATORY = ("H1a", "H1c", "H2c", "H3a", "RQ4.1", "RQ4.2", "RQ4.3", "RQ4.4")
EXPLORATORY = ("H1b", "H1c-lag")


def _fmt(value) -> str:
    if pd.isna(value):
        return "—"
    return f"{float(value):.6g}"


def _ci(row) -> str:
    if pd.isna(row["ci_low"]) or pd.isna(row["ci_high"]):
        return "—"
    return f"[{_fmt(row['ci_low'])}, {_fmt(row['ci_high'])}]"


def render_verdicts(stats: pd.DataFrame, floors: pd.DataFrame) -> str:
    lines = [
        "# protocol/HYPOTHESES_VERDICTS.md — post-freeze outcome record",
        "",
        "> Generated by `scripts/report_verdicts.py` from",
        "> `reports/tables/real_statistics.csv` and",
        "> `reports/tables/real_noise_floors.csv`. The frozen register is",
        "> `protocol/HYPOTHESES.md` and is not modified. Every value below",
        "> is read from a committed table; none is typed by hand.",
        ">",
        "> Confirmatory family: eight tests, Holm step-down applied once,",
        "> alpha = 0.05, two-sided. Precision is bounded by DEV-1",
        "> (five seed and five bootstrap refits per configuration): the",
        "> stability and group floors pool 100 pairs per family, and the",
        "> seed-flip floor pools 450 seed pairs per family. Every floor row",
        "> carries its exact n_pairs. DEV-2 relabels the H1c lag axis as",
        "> label age; DEV-3 adds the interpretable companions to H1c.",
        "",
        "## Confirmatory family",
        "",
        "| ID | Statistic | Estimate | 95% CI | p (raw) | p (Holm) | Verdict | Note |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for hyp in CONFIRMATORY:
        sub = stats[stats["hypothesis"] == hyp]
        if sub.empty:
            lines.append(f"| {hyp} | — | — | — | — | — | not run | — |")
            continue
        row = sub.iloc[0]
        lines.append(
            f"| {hyp} | {row['statistic']} | {_fmt(row['value'])} | "
            f"{_ci(row)} | {_fmt(row['p_raw'])} | {_fmt(row['p_holm'])} | "
            f"{row['verdict']} | {row.get('note', '')} |"
        )
    lines += ["", "## Exploratory and descriptive rows", "",
              "| ID | Statistic | Estimate | 95% CI | p (raw) | Note |",
              "|---|---|---|---|---|---|"]
    for hyp in EXPLORATORY:
        sub = stats[stats["hypothesis"] == hyp]
        if sub.empty:
            continue
        for _, row in sub.iterrows():
            lines.append(
                f"| {hyp} | {row['statistic']} | {_fmt(row['value'])} | "
                f"{_ci(row)} | {_fmt(row['p_raw'])} | {row.get('note', '')} |"
            )
    lines += ["", "## Noise-floor pair counts (DEV-1 precision)", "",
              "| Family | Dimension | Pairs |", "|---|---|---|"]
    for (fam, dim), sub in floors.groupby(["family", "dimension"]):
        lines.append(f"| {fam} | {dim} | {int(sub['n_pairs'].max())} |")
    lines += [
        "",
        "## Reading rules",
        "",
        "- `reject_H0` is a Holm-adjusted decision at 0.05; it is not a",
        "  statement about effect size. `not_rejected` is not evidence of",
        "  absence, especially under DEV-1's reduced floor precision.",
        "- H1c tests recovery against the within-cohort oracle: a CI that",
        "  excludes 1 supports partial recovery, whether the estimate is",
        "  near zero or near one. The ratio's denominator (oracle Brier",
        "  gain) is tiny for calibrated cohorts, so the mean is not an",
        "  interpretable magnitude; DEV-3's median recovery and mean Brier",
        "  change are the descriptive companions. A negative estimate means",
        "  the deployable arm scored worse than no recalibration; it is not",
        "  partial recovery and is reported with that sign.",
        "- RQ4.x deltas are paired against the AUC-to-AUC baseline on one",
        "  shared cluster-bootstrap design. Equivalence classifications use",
        "  the pre-registered |rho| < 0.3 region and apply to the outcome",
        "  correlation, not the delta.",
        "- The random-forest explanation outcomes use Brier-loss",
        "  permutation importance, not SHAP (DEV-1).",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    stats = pd.read_csv(TABLES / "real_statistics.csv")
    floors = pd.read_csv(TABLES / "real_noise_floors.csv")
    OUT.write_text(render_verdicts(stats, floors), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
